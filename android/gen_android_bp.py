class Resolver(object):
    def __init__(self, tree):
        self.tree = tree

    def closure(self, master_rel, base_dir):
        """Modules required to load `master_rel`.

        `base_dir` mirrors alsa-lib's uc_mgr->conf_dir_name: it is fixed for
        the whole load and is what relative includes resolve against.
        """
        mods, seen = set(), set()
        self._walk(master_rel, base_dir, mods, seen)
        return mods

    def _walk(self, rel, base_dir, mods, seen):
        if rel in seen:
            return
        seen.add(rel)

        if rel in self.tree.links:
            mods.add(self.tree.link_module(rel))
            target = os.path.normpath(
                os.path.join(os.path.dirname(rel), self.tree.links[rel]))
            self._walk(target, base_dir, mods, seen)
            return

        if not self.tree.isfile(rel):
            return

        d = os.path.dirname(rel)
        if self.tree.has_files(d):
            mods.add(self.tree.files_module(d))

        if not rel.endswith(".conf"):
            return

        text = self.tree.read(rel)
        for raw in RE_FILE.findall(text):
            self._handle_include(raw, base_dir, mods, seen)
        for raw in RE_INLINE.findall(text):
            self._handle_inline(raw, base_dir, mods, seen)
        for raw in RE_BLOB.findall(text):
            self._handle_blob(raw, mods)

    def _handle_include(self, raw, base_dir, mods, seen):
        if "${" in raw:
            # Not statically resolvable. Fall back to the longest static
            # directory prefix and pull in that whole subtree.
            static = raw.split("${")[0]
            d = static if static.endswith("/") else os.path.dirname(static)
            if not d:
                return
            d = self._resolve(d, base_dir)
            if d is not None and self.tree.isdir(d):
                mods.update(self.tree.subtree_modules(d))
            return

        target = self._resolve(raw, base_dir)
        if target is not None and self.tree.exists(target):
            self._walk(target, base_dir, mods, seen)

    def _handle_inline(self, raw, base_dir, mods, seen):
        # `<codecs/foo/Bar.conf>` is looked up in the ucm2 root first.
        if "${" not in raw and not raw.startswith("/") and \
                self.tree.exists(os.path.normpath(raw)):
            raw = "/" + raw
        self._handle_include(raw, base_dir, mods, seen)

    def _handle_blob(self, raw, mods):
        static = raw.split("${")[0]
        if not static:
            d = "blobs"
        elif static.endswith("/"):
            d = os.path.join("blobs", static)
        else:
            # a file name still has an extension at this point
            tail = os.path.basename(static)
            d = os.path.join("blobs",
                             os.path.dirname(static) if "." in tail else static)
        d = os.path.normpath(d)
        if self.tree.isdir(d):
            mods.update(self.tree.subtree_modules(d))

    @staticmethod
    def _resolve(path, base_dir):
        if path.startswith("/"):
            rel = os.path.normpath(path.lstrip("/"))
        else:
            rel = os.path.normpath(os.path.join(base_dir, path))
        if rel.startswith(".."):
            return None
        return "" if rel == "." else rel


