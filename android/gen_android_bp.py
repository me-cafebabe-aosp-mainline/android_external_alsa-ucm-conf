def emit_files(tree, rel, bp_dir):
    """`rel` and `bp_dir` are both relative to ucm2/.

    Soong resolves srcs relative to the directory holding the Android.bp, so
    the paths have to be rebased onto `bp_dir`.
    """
    prefix = rel[len(bp_dir):].lstrip("/") if bp_dir else rel
    srcs = [os.path.join(prefix, f) if prefix else f for f in tree.files[rel]]
    dest = RELATIVE_INSTALL_PATH + ("/" + rel if rel else "")
    return bp_module("prebuilt_etc", [
        bp_str("name", tree.files_module(rel)),
        bp_bool("vendor", True),
        bp_str("relative_install_path", dest),
        bp_strlist("srcs", srcs),
    ])


def emit_link(tree, rel):
    return bp_module("install_symlink", [
        bp_str("name", tree.link_module(rel)),
        bp_bool("vendor", True),
        bp_str("installed_location", "%s/%s" % (INSTALL_LOCATION_ROOT, rel)),
        bp_str("symlink_target", tree.links[rel]),
    ])


def emit_phony(name, required):
    return bp_module("phony", [
        bp_str("name", name),
        bp_strlist("required", required),
    ])


def emit_package():
    return bp_module("package", [
        bp_strlist("default_applicable_licenses", [LICENSE_MODULE]),
    ])


def emit_skipped(skipped, where):
    """Comment block documenting entries that cannot be installed."""
    if not skipped:
        return ""
    lines = [
        "NOT installable by the Android build (%s):" % where,
        "",
        "Kati/Make treats whitespace as a list separator, so a path that",
        "contains a space cannot be installed, whatever the module type.",
        "alsa-lib probes for these by ${CardLongName}; a device that needs",
        "one of them has to provide it by other means, e.g. a device",
        "specific conf.d/<driver>/<driver>.conf that dispatches on the",
        "card long name.",
        "",
    ]
    lines += ["  ucm2/%s" % p for p, _ in skipped]
    return comment("\n".join(lines))


def join(blocks):
    return "\n".join(b.rstrip("\n") + "\n" for b in blocks if b)


def generate_subdir_bp(tree, top):
    """Android.bp covering the whole subtree of one top level ucm2 directory."""
    def inside(rel):
        return rel == top or rel.startswith(top + "/")

    dirs = [d for d in tree.all_dirs() if inside(d)]
    blocks = [HEADER, emit_package(),
              emit_skipped(tree.skipped_in(top, recursive=True),
                           "ucm2/%s" % top)]

    for d in dirs:
        if tree.has_files(d):
            blocks.append(emit_files(tree, d, top))

    for link in sorted(l for l in tree.links if inside(os.path.dirname(l))):
        blocks.append(emit_link(tree, link))

    for d in dirs:
        mods = tree.subtree_modules(d)
        if mods:
            blocks.append(comment("Everything below ucm2/%s/." % d)
                          + emit_phony(tree.dir_module(d), mods))

    return join(blocks)


def generate_ucm2_bp(tree, cards):
    """Android.bp for ucm2/ itself: root files, the base module and the cards."""
    blocks = [HEADER, emit_package()]

    if tree.has_files(""):
        blocks.append(emit_files(tree, "", ""))
    for link in sorted(l for l in tree.links if not os.path.dirname(l)):
        blocks.append(emit_link(tree, link))

    base = []
    if tree.has_files(""):
        base.append(tree.files_module(""))
    base += tree.subtree_modules("lib")
    blocks.append(
        comment("The toplevel lookup file plus the private alsa-lib helpers\n"
                "it includes. Required by every other module here.")
        + emit_phony("%s-base" % PREFIX, sorted(set(base))))

    blocks.append(comment(
        "-------------------------------------------------------------------\n"
        "Per sound card modules.\n"
        "\n"
        "<name> is the ucm2/conf.d/<name> directory, which alsa-lib probes\n"
        "with the ALSA driver name (`cat /proc/asound/cards`) and, as a\n"
        "fallback, with the kernel driver name (the basename of\n"
        "/sys/class/sound/card0/device/driver).\n"
        "\n"
        "The required list is the transitive closure of the Include\n"
        "statements of the card configuration, so a device only installs\n"
        "what that one card actually needs.\n"
        "-------------------------------------------------------------------")
        .rstrip("\n"))

    for card in cards:
        text = list(card.entries)
        if card.skipped:
            if text:
                text.append("")
            text.append("NOT installed, path contains whitespace "
                        "(see ucm2/conf.d/Android.bp):")
            text += ["  %s" % p for p in card.skipped]
            if not card.entries:
                text.append("")
                text.append("This module is intentionally empty.")
        blocks.append(
            comment("\n".join(text))
            + emit_phony(card.module,
                         ["%s-base" % PREFIX] + list(card.deps)))

    return join(blocks)


def generate_root_bp(tree, tops):
    doc = """\
Android build rules for alsa-ucm-conf, the ALSA Use Case Manager
configuration database.

Everything is installed below /vendor/etc/alsa/ucm2, which is where our
alsa-lib build looks for it (ALSA_CONFIG_DIR "/ucm2"). The ALSA_CONFIG_UCM2
environment variable can override the location at runtime.

Nothing is installed unless a product asks for it. Pick the granularity that
suits the device:

  # 1. a single sound card (recommended)
  #    <name> is the ucm2/conf.d/<name> directory, i.e. the ALSA driver name
  #    from /proc/asound/cards with the kernel driver name as a fallback.
  #    This pulls in the transitive closure of the card configuration and
  #    nothing else.
  PRODUCT_PACKAGES += alsa-ucm-conf-card-sm8650

  # 2. a whole directory subtree
  PRODUCT_PACKAGES += alsa-ucm-conf-dir-Qualcomm

  # 3. one directory, non recursive
  PRODUCT_PACKAGES += alsa-ucm-conf-files-codecs_wcd938x

  # 4. everything, mostly useful during bring-up
  PRODUCT_PACKAGES += alsa-ucm-conf-all

`android/gen_android_bp.py --list` prints every selectable module name.

Known limitation: upstream names a few configurations after the card long
name, which contains spaces (e.g. conf.d/tegra/Compal PAZ00.conf). Kati/Make
cannot install paths with whitespace, so those are skipped. Each affected
Android.bp lists them in a comment near the top."""

    blocks = [
        HEADER + "//\n" + comment(doc),
        emit_package(),
        bp_module("license", [
            bp_str("name", LICENSE_MODULE),
            bp_strlist("visibility", [":__subpackages__"]),
            bp_strlist("license_kinds", ["SPDX-license-identifier-BSD-3-Clause"]),
            bp_strlist("license_text", ["LICENSE"]),
        ]),
        comment("Every configuration shipped by alsa-ucm-conf.")
        + emit_phony("%s-all" % PREFIX,
                     ["%s-base" % PREFIX]
                     + [tree.dir_module(t) for t in tops]),
    ]
    return join(blocks)


