def find_bpfmt():
    bpfmt = shutil.which("bpfmt")
    if bpfmt:
        return bpfmt
    top = os.environ.get("ANDROID_BUILD_TOP")
    candidates = ["prebuilts/build-tools/linux-x86/bin/bpfmt",
                  "out/host/linux-x86/bin/bpfmt"]
    for cand in candidates:
        path = os.path.join(top, cand) if top else cand
        if os.path.exists(path):
            return path
    return None


def format_bp(content, bpfmt):
    """Canonicalise through bpfmt so that --check is stable."""
    if not bpfmt:
        return content
    res = subprocess.run([bpfmt, "-o"], input=content, capture_output=True,
                         text=True)
    if res.returncode != 0:
        sys.stderr.write(res.stderr)
        raise SystemExit("bpfmt rejected the generated output")
    return res.stdout


def build(root):
    tree = Tree(root)
    cards = collect_cards(tree)
    # directories that hold nothing installable (conf.virt.d is empty upstream)
    # must not produce an empty Android.bp or a dangling phony
    tops = [t for t in tree.subdirs[""] if tree.subtree_modules(t)]

    outputs = {
        "Android.bp": generate_root_bp(tree, tops),
        os.path.join(UCM2, "Android.bp"): generate_ucm2_bp(tree, cards),
    }
    for top in tops:
        outputs[os.path.join(UCM2, top, "Android.bp")] = \
            generate_subdir_bp(tree, top)
    return tree, cards, outputs


def check_unique(tree, cards):
    names = {}

    def add(name, what):
        if name in names:
            raise SystemExit("duplicate module name %r: %s and %s"
                             % (name, names[name], what))
        names[name] = what

    for rel in tree.all_dirs():
        if tree.has_files(rel):
            add(tree.files_module(rel), "files:" + (rel or "<root>"))
    for rel in sorted(tree.links):
        add(tree.link_module(rel), "link:" + rel)
    for rel in tree.all_dirs():
        if tree.subtree_modules(rel):
            add(tree.dir_module(rel), "dir:" + (rel or "<root>"))
    for card in cards:
        add(card.module, "card:" + card.name)
    return names


def do_list(cards, names):
    print("# always required")
    print("%s-base" % PREFIX)
    print("%s-all" % PREFIX)
    print("\n# per card (ucm2/conf.d/<name>)")
    for card in cards:
        print(card.module)
    print("\n# per directory subtree")
    for name in sorted(n for n, w in names.items() if w.startswith("dir:")):
        print(name)
    print("\n# per directory, non recursive")
    for name in sorted(n for n, w in names.items() if w.startswith("files:")):
        print(name)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-C", "--root",
                    help="alsa-ucm-conf source root "
                         "(default: the parent directory of this script)")
    ap.add_argument("--check", action="store_true",
                    help="do not write anything, exit 1 if out of date")
    ap.add_argument("--list", action="store_true",
                    help="print the selectable module names and exit")
    ap.add_argument("--no-bpfmt", action="store_true",
                    help="skip the bpfmt canonicalisation step")
    args = ap.parse_args()

    root = args.root or os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    if not os.path.isdir(os.path.join(root, UCM2)):
        raise SystemExit("%s does not look like an alsa-ucm-conf tree" % root)

    tree, cards, outputs = build(root)
    names = check_unique(tree, cards)

    if args.list:
        do_list(cards, names)
        return 0

    if tree.skipped and not args.check:
        sys.stderr.write(
            "warning: %d entries skipped, the Android build cannot install "
            "paths with whitespace:\n" % len(tree.skipped))
        for path, _ in tree.skipped:
            sys.stderr.write("  ucm2/%s\n" % path)

    bpfmt = None if args.no_bpfmt else find_bpfmt()
    outputs = {rel: format_bp(text, bpfmt) for rel, text in outputs.items()}

    stale, written = [], 0
    for rel, content in sorted(outputs.items()):
        path = os.path.join(root, rel)
        old = None
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as fp:
                old = fp.read()
        if old == content:
            continue
        if args.check:
            stale.append(rel)
            continue
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as fp:
            fp.write(content)
        written += 1

    if args.check:
        if stale:
            sys.stderr.write("out of date, rerun %s:\n  %s\n"
                             % (SCRIPT, "\n  ".join(stale)))
            return 1
        sys.stderr.write("%d Android.bp files are up to date\n" % len(outputs))
        return 0

    def count(kind):
        return sum(1 for w in names.values() if w.startswith(kind))

    sys.stderr.write(
        "%d Android.bp files (%d written): "
        "%d prebuilt_etc, %d install_symlink, %d dir phonies, %d card phonies"
        "%s\n"
        % (len(outputs), written, count("files:"), count("link:"),
           count("dir:"), len(cards),
           "" if bpfmt else " (bpfmt not found, output not canonicalised)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
