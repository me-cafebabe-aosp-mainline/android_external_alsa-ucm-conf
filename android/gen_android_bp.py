class Card(object):
    def __init__(self, name, module, deps, entries, skipped=()):
        self.name = name
        self.module = module
        self.deps = deps
        self.entries = entries
        self.skipped = list(skipped)


def collect_cards(tree):
    resolver = Resolver(tree)
    cards = []

    for probe in ("conf.d", "conf.virt.d"):
        if not tree.isdir(probe):
            continue

        # a whole probe directory may itself be a symlink, e.g.
        # conf.d/sof-skl_hda_card -> sof-hda-dsp
        for link in tree.links_in(probe):
            if not tree.link_is_dir.get(link):
                continue
            name = os.path.basename(link)
            alias = os.path.basename(tree.links[link].rstrip("/"))
            cards.append(Card(
                name, tree.card_module(name),
                sorted({tree.link_module(link), tree.card_module(alias)}),
                ["%s -> %s" % (link, tree.links[link])]))

        for sub in tree.subdirs.get(probe, []):
            name = os.path.basename(sub)
            deps, entries = set(), []

            for basename in tree.files.get(sub, []):
                rel = os.path.join(sub, basename)
                entries.append(rel)
                deps |= resolver.closure(rel, sub)

            for link in tree.links_in(sub):
                deps.add(tree.link_module(link))
                target = os.path.normpath(os.path.join(sub, tree.links[link]))
                entries.append("%s -> %s" % (link, tree.links[link]))
                deps |= resolver.closure(target, os.path.dirname(target))

            skipped = [p for p, _ in tree.skipped_in(sub)]

            if deps:
                cards.append(Card(name, tree.card_module(name),
                                  sorted(deps), sorted(entries), skipped))
            elif skipped:
                # every entry of this card is uninstallable; still emit a
                # module so the name exists, and make the situation obvious
                cards.append(Card(name, tree.card_module(name), [], [],
                                  skipped))

    cards.sort(key=lambda c: c.name)
    return cards


