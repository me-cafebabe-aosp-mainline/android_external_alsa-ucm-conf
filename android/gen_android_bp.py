class Tree(object):
    def __init__(self, root):
        self.root = root
        self.ucm2 = os.path.join(root, UCM2)
        self.files = {}         # rel dir -> [basename, ...]  (installable)
        self.subdirs = {}       # rel dir -> [rel child dir, ...] (real dirs)
        self.links = {}         # rel path -> raw link target
        self.link_is_dir = {}   # rel path -> bool
        self.skipped = []       # [(rel path, reason), ...] not installable
        self._scan("")

    def _scan(self, rel):
        abs_dir = os.path.join(self.ucm2, rel) if rel else self.ucm2
        files, subdirs = [], []
        for entry in sorted(os.scandir(abs_dir), key=lambda e: e.name):
            child = os.path.join(rel, entry.name) if rel else entry.name
            if not RE_SAFE_COMPONENT.match(entry.name):
                if entry.name in SKIP_BASENAMES:
                    continue
                kind = ("symlink" if entry.is_symlink()
                        else "directory" if entry.is_dir() else "file")
                self.skipped.append(
                    (child, "%s name contains characters the Android build "
                            "cannot install" % kind))
                continue
            if entry.is_symlink():
                self.links[child] = os.readlink(entry.path)
                self.link_is_dir[child] = os.path.isdir(entry.path)
            elif entry.is_dir():
                subdirs.append(child)
                self._scan(child)
            elif (entry.name not in SKIP_BASENAMES
                  and not entry.name.endswith(SKIP_SUFFIXES)):
                files.append(entry.name)
        self.files[rel] = files
        self.subdirs[rel] = subdirs

    # -- module names ------------------------------------------------------

    def files_module(self, rel):
        return "%s-files-%s" % (PREFIX, sanitize(rel))

    def link_module(self, rel):
        base = rel[:-5] if rel.endswith(".conf") else rel
        return "%s-link-%s" % (PREFIX, sanitize(base))

    def dir_module(self, rel):
        return "%s-dir-%s" % (PREFIX, sanitize(rel))

    def card_module(self, name):
        return "%s-card-%s" % (PREFIX, sanitize(name))

    # -- queries -----------------------------------------------------------

    def has_files(self, rel):
        return bool(self.files.get(rel))

    def links_in(self, rel):
        pfx = (rel + "/") if rel else ""
        return sorted(l for l in self.links
                      if l.startswith(pfx) and "/" not in l[len(pfx):])

    def all_dirs(self):
        return sorted(self.files)

    def skipped_in(self, rel, recursive=False):
        """Skipped entries directly below (or anywhere below) `rel`."""
        pfx = (rel + "/") if rel else ""
        out = []
        for path, reason in self.skipped:
            if not path.startswith(pfx):
                continue
            if not recursive and "/" in path[len(pfx):]:
                continue
            out.append((path, reason))
        return out

    def subtree_modules(self, rel):
        """Module names that install the complete subtree of `rel`."""
        mods = []
        if self.has_files(rel):
            mods.append(self.files_module(rel))
        mods.extend(self.link_module(l) for l in self.links_in(rel))
        for sub in self.subdirs.get(rel, []):
            mods.extend(self.subtree_modules(sub))
        return mods

    def exists(self, rel):
        return os.path.lexists(os.path.join(self.ucm2, rel))

    def isfile(self, rel):
        return os.path.isfile(os.path.join(self.ucm2, rel))

    def isdir(self, rel):
        return os.path.isdir(os.path.join(self.ucm2, rel))

    def read(self, rel):
        with open(os.path.join(self.ucm2, rel), "r",
                  encoding="utf-8", errors="replace") as fp:
            return fp.read()


