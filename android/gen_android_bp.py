"""Generate the Android.bp files for alsa-ucm-conf.

alsa-ucm-conf is a pure data package: ~660 *.conf files, a handful of binary
blobs and 156 symlinks spread over 340 directories.  Shipping all of it on a
device is wasteful and hand writing Soong rules for it is not maintainable,
so the build files are generated from the source tree by this script.

Device layout
-------------

    /vendor/etc/alsa/ucm2/<the upstream ucm2/ layout>

which is where our alsa-lib build looks for it (ALSA_CONFIG_DIR "/ucm2", see
src/ucm/utils.c:uc_mgr_config_dir()).

Generated modules
-----------------

    alsa-ucm-conf-base              ucm2/ucm.conf + ucm2/lib/*, always needed
    alsa-ucm-conf-all               everything

    alsa-ucm-conf-files-<DIR>       prebuilt_etc, the regular files of one
                                    directory (non recursive)
    alsa-ucm-conf-link-<PATH>       install_symlink, one upstream symlink
    alsa-ucm-conf-dir-<DIR>         phony, the whole subtree of one directory
    alsa-ucm-conf-card-<DRIVER>     phony, one ucm2/conf.d/<DRIVER> entry plus
                                    the transitive closure of everything that
                                    entry includes

A device normally only needs the card module of its sound card:

    PRODUCT_PACKAGES += alsa-ucm-conf-card-sm8650

Why the symlinks are installed as symlinks
------------------------------------------

They must not be dereferenced.  alsa-lib readlink()s the master UCM file (see
the S_ISLNK branch in src/ucm/parser.c) and uses the *link target's* directory
as the base directory for every relative Include afterwards.  Installing a
copy instead of the link would silently break every relative include of that
card.

Dependency computation
----------------------

For every conf.d entry the script follows `Include.<id>.File "..."` and the
inline `<path/to/file.conf>` includes (looked up in the ucm2 root first):

  * "/foo/bar.conf"  is resolved against the ucm2 root
  * "foo/bar.conf"   is resolved against the *master file's* directory.  Note
                     that alsa-lib keeps uc_mgr->conf_dir_name fixed for the
                     whole load, relative includes are not relative to the
                     including file.
  * paths containing ${...} cannot be resolved statically, so the longest
    static directory prefix is taken and that whole subtree is pulled in.

Binary blobs referenced as "${ConfTopDir}/blobs/..." by cset-bin sequences are
picked up with a separate pattern.

Known limitation: paths with whitespace
---------------------------------------

Soong hands every installed path to Kati as a whitespace separated Make list
(LOCAL_ADDITIONAL_DEPENDENCIES, LOCAL_SOONG_INSTALL_PAIRS,
LOCAL_SOONG_INSTALL_SYMLINKS, ...).  A path containing a space therefore
cannot be installed by the Android build, whatever the module type.  Upstream
names some configurations after the card long name, e.g.
"conf.d/tegra/Compal PAZ00.conf" or "NXP/iMX8/Librem_5/Librem 5.conf".  Such
entries are skipped, reported on stderr and listed in a comment of the
generated Android.bp so that they stay discoverable.  A device that needs one
of them has to provide it through other means, e.g. a device specific
conf.d/<driver>/<driver>.conf that dispatches on ${CardLongName}.

Usage
-----

    android/gen_android_bp.py            # (re)generate the Android.bp files
    android/gen_android_bp.py --check    # fail if they are out of date
    android/gen_android_bp.py --list     # print the selectable module names
"""

import argparse
import os
import re
import shutil
import signal
import subprocess
import sys

# `--list | head` should not produce a traceback
if hasattr(signal, "SIGPIPE"):
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)

# --------------------------------------------------------------------------
# configuration
# --------------------------------------------------------------------------

UCM2 = "ucm2"

# install destination, relative to the partition root / to <partition>/etc
INSTALL_LOCATION_ROOT = "etc/alsa/ucm2"
RELATIVE_INSTALL_PATH = "alsa/ucm2"

PREFIX = "alsa-ucm-conf"
LICENSE_MODULE = "external_alsa_ucm_conf_license"

# documentation, build files and VCS noise: never installed. Android.bp has to
# be listed here or the second run of this script would pick up the files it
# generated itself.
SKIP_BASENAMES = {".gitignore", "Android.bp", "Android.mk", "AndroidProducts.mk"}
SKIP_SUFFIXES = (".md",)

SCRIPT = "android/gen_android_bp.py"

HEADER = ("// Generated by %s -- do not edit.\n"
          "//\n"
          "// To regenerate, run the following from the alsa-ucm-conf root:\n"
          "//\n"
          "//     %s\n" % (SCRIPT, SCRIPT))

# Characters that are safe in a path handed to Kati/Make and Ninja.  Whitespace
# splits Make lists, the rest are Make/Ninja/shell metacharacters.  A comma is
# fine: $(call)/$(patsubst) split their arguments before expansion.
RE_SAFE_COMPONENT = re.compile(r'^[A-Za-z0-9._+,@-]+$')

# `Include.<id>.File "..."` and any other bare `File "..."`
RE_FILE = re.compile(r'\bFile\s+"([^"]+)"')
# inline `<path/to/file.conf>` include, one per line
RE_INLINE = re.compile(r'^\s*<([^<>\s]+)>\s*(?:#.*)?$', re.M)
# binary blobs, referenced as "${ConfTopDir}/blobs/..." by cset-bin
RE_BLOB = re.compile(r'"[^"]*\bblobs/([^"]*)"')


# --------------------------------------------------------------------------
# small helpers
# --------------------------------------------------------------------------

def sanitize(rel):
    """Turn a path relative to ucm2/ into a module name fragment."""
    if rel in ("", "."):
        return "root"
    out = []
    for ch in rel:
        if ch.isalnum() or ch in "-.":
            out.append(ch)
        elif ch == "/":
            out.append("_")
        elif ch == "+":
            out.append("_plus_")
        else:
            out.append("_")
    return "".join(out)


def bp_strlist(name, items, indent=4):
    pad = " " * indent
    inner = " " * (indent + 4)
    body = "".join('%s"%s",\n' % (inner, i) for i in items)
    return "%s%s: [\n%s%s],\n" % (pad, name, body, pad)


def bp_module(kind, props):
    """props is a list of already rendered `    key: value,\\n` strings."""
    return "%s {\n%s}\n" % (kind, "".join(props))


def bp_str(name, value, indent=4):
    return '%s%s: "%s",\n' % (" " * indent, name, value)


def bp_bool(name, value, indent=4):
    return "%s%s: %s,\n" % (" " * indent, name, "true" if value else "false")


def comment(text):
    return "".join("// %s\n" % line if line else "//\n"
                   for line in text.splitlines())


